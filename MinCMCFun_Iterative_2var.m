function [TC,S,f2s] = MinCMCFun_Iterative_2var(mu1,mu2,mu1_rw,mu2_rw,U,L,SIGMA)
% used by MinimiseCMCFunction_2Var.m
% determine scrap and rework cost for a 2 variable example given the means.

RC = [0 25 25 50];
C = 1;
mu1_R = L(1)+(U(1)-mu1);
mu2_R = L(2)+(U(2)-mu2);
sig11 = sqrt(SIGMA(1,1));
sig22 = sqrt(SIGMA(2,2));


FU1U2 = mvncdf([U(1),U(2)],[mu1_R mu2_R],SIGMA);
FL1U2 = mvncdf([L(1),U(2)],[mu1_R mu2_R],SIGMA);
FU1L2 = mvncdf([U(1),L(2)],[mu1_R mu2_R],SIGMA);
FL1L2 = mvncdf([L(1),L(2)],[mu1_R mu2_R],SIGMA);
        
InitialScr = 1 - FU1U2;
InitialRw2 = FL1U2 - FL1L2;
InitialRw3 = FU1L2 - FL1L2;
InitialRw4 = FL1L2;

for i = 1:100
    IterRw4_v(i) = FL1L2*(FL1L2^(i-1));
end
IterRw4 = sum([IterRw4_v]);

%IterSr2(1) = InitialRw2*(normcdf(L(1),mu1,sig11))
for i = 1:100
%    IterSr2(2) = (1-normcdf(U(1),mu1,sig11)+FL1L2*InitialRw2)*
    Sr2Iter(i) = (normcdf(L(1),mu1_rw,sig11))*(1-normcdf(U(1),mu1_rw,sig11))^(i-1);
    FeedFrom4to2(i) = FL1L2^i*InitialRw2;
end
sum(Sr2Iter)
sum(FeedFrom4to2)
IterSr2 = sum([Sr2Iter])*(sum([FeedFrom4to2])+InitialRw2);
for i = 1:100
    %IterSr3_v(i) = (normcdf(L(2),mu2,sig22))*((InitialRw3*(1-normcdf(U(2),mu2,sig22))^(i-1))+FL1L2^i*InitialRw2);
    Sr3Iter(i) = (normcdf(L(2),mu2_rw,sig22))*(1-normcdf(U(2),mu2_rw,sig22))^(i-1);
    FeedFrom4to3(i) = FL1L2^i*InitialRw3;
end
IterSr3 = sum([Sr3Iter])*(sum([FeedFrom4to3])+InitialRw3);
for i = 1:100
    IterSr4_v(i) = (1 - FU1U2)*(FL1L2^i);
end
IterSr4 = sum([IterSr4_v]);
%% REWORK
Rw2Iter(1) = InitialRw2; % rework from initial process get done here
for i = 2:100
   Rw2Iter(i) = Rw2Iter(i-1)*(1-normcdf(U(1),mu1_rw,sig11))+FL1L2^(i-1)*InitialRw2;
   %'Rw2Iter(i)' is rework from previous iteration 'Rw2Iter1(i-1)' 
   % multiplied by prob of single feature rework '(1-normcdf(U(1),mu1,sig11))'
   % PLUS the rewrok that comes in from state 4. This rework from state 4
   % get added onto the rework generated by state 2
end
IterRw2 = sum([Rw2Iter])

Rw3Iter(1) = InitialRw3; % rework from initial process get done here
for i = 2:100
    Rw3Iter(i) = Rw3Iter(i-1)*(1-normcdf(U(2),mu2_rw,sig22))+FL1L2^(i-1)*InitialRw3;
end
IterRw3 = sum([Rw3Iter]);
SC = [100, 100+25*(1+IterRw2), 100+25*(1+IterRw3), 100+50*(1+IterRw4)];
Scrap = SC(1)*InitialScr + SC(2)*IterSr2 + SC(3)*IterSr3 + SC(4)*IterSr4;
Rwork = RC(2)*IterRw2 + RC(3)*IterRw3 + RC(4)*IterRw4;

TC = Scrap + Rwork;

f2s = [IterSr2,IterSr3,IterSr4];

S = struct('Scrap',Scrap,'Rwork',Rwork,...
           'Sc1',SC(1)*InitialScr,'Sc2',SC(2)*IterSr2,...
           'Sc3',SC(3)*IterSr3,'Sc4',SC(4)*IterSr4,...
           'Rw1',RC(2)*IterRw2,...
           'Rw2',RC(3)*IterRw3,...
           'Rw3',RC(4)*IterRw4);

